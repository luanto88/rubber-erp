-- ISO standards, document type master data, and review workflow fields.

CREATE TABLE IF NOT EXISTS iso_standards (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tieu_chuan      TEXT NOT NULL UNIQUE,
  ten_tieu_chuan  TEXT NOT NULL,
  is_active       BOOLEAN NOT NULL DEFAULT true,
  sort_order      INTEGER NOT NULL DEFAULT 0,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE iso_standards ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "iso_standards_read" ON iso_standards;
CREATE POLICY "iso_standards_read" ON iso_standards
  FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS "iso_standards_admin_manage" ON iso_standards;
CREATE POLICY "iso_standards_admin_manage" ON iso_standards
  FOR ALL TO authenticated
  USING (EXISTS (SELECT 1 FROM profiles WHERE profiles.id = auth.uid() AND profiles.role = 'admin'))
  WITH CHECK (EXISTS (SELECT 1 FROM profiles WHERE profiles.id = auth.uid() AND profiles.role = 'admin'));

