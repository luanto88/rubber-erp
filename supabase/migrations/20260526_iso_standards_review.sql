CREATE TABLE IF NOT EXISTS iso_document_standards (
  doc_id       UUID NOT NULL REFERENCES iso_documents(id) ON DELETE CASCADE,
  standard_id  INTEGER NOT NULL REFERENCES iso_standards(id) ON DELETE RESTRICT,
  factory_id   UUID NOT NULL REFERENCES factories(id) ON DELETE CASCADE,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (doc_id, standard_id)
);

CREATE INDEX IF NOT EXISTS idx_iso_document_standards_factory_standard
  ON iso_document_standards(factory_id, standard_id);

ALTER TABLE iso_document_standards ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "iso_document_standards_factory" ON iso_document_standards;
CREATE POLICY "iso_document_standards_factory" ON iso_document_standards
  FOR ALL USING (
    factory_id IN (SELECT factory_id FROM profiles WHERE id = auth.uid())
  )
  WITH CHECK (
    factory_id IN (SELECT factory_id FROM profiles WHERE id = auth.uid())
  );

CREATE TABLE IF NOT EXISTS iso_document_types (
  code                 TEXT PRIMARY KEY,
  name                 TEXT NOT NULL,
  can_parent           BOOLEAN NOT NULL DEFAULT true,
