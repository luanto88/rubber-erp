export function palletLabel(lang: Lang, value: string): string {
  if (lang !== "km") return value;
  return PALLET_LABEL_KM[value] ?? value;
}

export function t(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const raw = DICT[lang]?.[key] ?? DICT.vi[key] ?? key;
  if (!vars) return raw;
  return Object.entries(vars).reduce(
    (acc, [k, v]) => acc.replaceAll(`{${k}}`, String(v)),
    raw,
  );
}

export function loadStoredLang(): Lang {
  if (typeof window === "undefined") return "vi";
  const stored = window.localStorage.getItem(LANG_STORAGE_KEY);
  return stored === "km" ? "km" : "vi";
}

export function storeLang(lang: Lang) {
  if (typeof window === "undefined") return;
  window.localStorage.setItem(LANG_STORAGE_KEY, lang);
}
